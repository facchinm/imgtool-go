const autogenMessage = "/* Autogenerated by imgtool.py, do not edit. */"

type KeyKind int

const (
	KindRSA KeyKind = iota
	KindECDSA256
	KindECDSA384
	KindEd25519
	KindX25519
)

// Key wraps a private or public key of one of the supported types.
type Key struct {
	Kind KeyKind
	Priv crypto.Signer // nil for public-only and X25519 keys
	Pub  crypto.PublicKey

	ECDHPriv *ecdh.PrivateKey // X25519 private key
}

var keyTypes = []string{"rsa-2048", "rsa-3072", "ecdsa-p256", "ecdsa-p384", "ed25519", "x25519"}

func GenerateKey(typ string) (*Key, error) {
	var s crypto.Signer
	var err error
	switch typ {
	case "rsa-2048":
		s, err = rsa.GenerateKey(rand.Reader, 2048)
	case "rsa-3072":
		s, err = rsa.GenerateKey(rand.Reader, 3072)
	case "ecdsa-p256":
		s, err = ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	case "ecdsa-p384":
		s, err = ecdsa.GenerateKey(elliptic.P384(), rand.Reader)
	case "ed25519":
		_, s, err = ed25519.GenerateKey(rand.Reader)
	case "x25519":
		p, err := ecdh.X25519().GenerateKey(rand.Reader)
		if err != nil {
			return nil, err
		}
		return &Key{Kind: KindX25519, Pub: p.PublicKey(), ECDHPriv: p}, nil
	default:
		return nil, fmt.Errorf("unknown key type %q", typ)
	}
	if err != nil {
		return nil, err
	}
	return keyFrom(s, s.Public())
}

func keyFrom(priv crypto.Signer, pub crypto.PublicKey) (*Key, error) {
	k := &Key{Priv: priv, Pub: pub}
	switch p := pub.(type) {
	case *rsa.PublicKey:
		if p.N.BitLen() != 2048 && p.N.BitLen() != 3072 {
			return nil, fmt.Errorf("unsupported RSA key size: %d", p.N.BitLen())
		}
		k.Kind = KindRSA
	case *ecdsa.PublicKey:
		switch p.Curve {
		case elliptic.P256():
			k.Kind = KindECDSA256
		case elliptic.P384():
			k.Kind = KindECDSA384
		default:
			return nil, fmt.Errorf("unsupported EC curve: %s", p.Curve.Params().Name)
		}
	case ed25519.PublicKey:
		k.Kind = KindEd25519
	case *ecdh.PublicKey:
		if p.Curve() != ecdh.X25519() {
			return nil, errors.New("unsupported ECDH curve")
		}
		k.Kind = KindX25519
	default:
		return nil, fmt.Errorf("unknown key type %T", pub)
	}
	return k, nil
}

// LoadKey reads an unencrypted PEM private or public key. It returns
// errPasswordRequired for password-protected keys.
func LoadKey(path string) (*Key, error) { return LoadKeyPassword(path, nil) }

// LoadKeyPassword reads a PEM key, decrypting it with password when it is
// password-protected (PKCS#8 PBES2 or legacy OpenSSL "Proc-Type: 4,ENCRYPTED").
func LoadKeyPassword(path string, password []byte) (*Key, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	for len(raw) > 0 {
		var blk *pem.Block
		blk, raw = pem.Decode(raw)
		if blk == nil {
			break
		}
		//lint:ignore SA1019 legacy encrypted PEM is still accepted by upstream
		if x509.IsEncryptedPEMBlock(blk) {
			if password == nil {
				return nil, errPasswordRequired
			}
			//lint:ignore SA1019 see above
			der, err := x509.DecryptPEMBlock(blk, password)
			if err != nil {
				return nil, errBadPassword
			}
			blk = &pem.Block{Type: blk.Type, Bytes: der}
		}
		if blk.Type == "ENCRYPTED PRIVATE KEY" {
			if password == nil {
				return nil, errPasswordRequired
			}
			der, err := decryptPKCS8(blk.Bytes, password)
			if err != nil {
				return nil, err
			}
			blk = &pem.Block{Type: "PRIVATE KEY", Bytes: der}
		}
		switch blk.Type {
		case "PRIVATE KEY":
			pk, err := x509.ParsePKCS8PrivateKey(blk.Bytes)
			if err != nil {
				return nil, err
			}
			if xp, ok := pk.(*ecdh.PrivateKey); ok {
				k, err := keyFrom(nil, xp.PublicKey())
				if err != nil {
					return nil, err
				}
				k.ECDHPriv = xp
				return k, nil
			}
			s, ok := pk.(crypto.Signer)
			if !ok {
				return nil, errors.New("unsupported private key type")
			}
			return keyFrom(s, s.Public())
		case "RSA PRIVATE KEY":
			pk, err := x509.ParsePKCS1PrivateKey(blk.Bytes)
			if err != nil {
				return nil, err
			}
			return keyFrom(pk, &pk.PublicKey)
		case "EC PRIVATE KEY":
			pk, err := x509.ParseECPrivateKey(blk.Bytes)
			if err != nil {
				return nil, err
			}
			return keyFrom(pk, &pk.PublicKey)
		case "PUBLIC KEY":
			pub, err := x509.ParsePKIXPublicKey(blk.Bytes)
			if err != nil {
				return nil, err
			}
			return keyFrom(nil, pub)
		case "RSA PUBLIC KEY":
			pub, err := x509.ParsePKCS1PublicKey(blk.Bytes)
			if err != nil {
				return nil, err
			}
			return keyFrom(nil, pub)
		}
	}
	return nil, fmt.Errorf("%s: no supported PEM key found", path)
}

func (k *Key) HasPrivate() bool { return k.Priv != nil || k.ECDHPriv != nil }

// CanSign reports whether the key is a signing private key.
func (k *Key) CanSign() bool { return k.Priv != nil }

func (k *Key) rsaBits() int { return k.Pub.(*rsa.PublicKey).N.BitLen() }

func (k *Key) ShortName() string {
	switch k.Kind {
	case KindRSA:
		return "rsa"
	case KindECDSA256:
		return "ecdsa"
	case KindECDSA384:
		return "ecdsap384"
	}
	if k.Kind == KindX25519 {
		return "x25519"
	}
	return "ed25519"
}

// PublicBytes returns the DER form embedded in MCUboot (PKCS1 for RSA,
// SubjectPublicKeyInfo otherwise).
func (k *Key) PublicBytes() []byte {
	if p, ok := k.Pub.(*rsa.PublicKey); ok {
		return x509.MarshalPKCS1PublicKey(p)
	}
	b, _ := x509.MarshalPKIXPublicKey(k.Pub)
	return b
}

func (k *Key) PublicPEM() []byte {
	b, _ := x509.MarshalPKIXPublicKey(k.Pub)
	return pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: b})
}

// PrivatePEM emits the private key as PKCS#8 PEM, encrypted when password is non-nil.
func (k *Key) PrivatePEM(password []byte) ([]byte, error) {
	var priv any = k.Priv
	if k.ECDHPriv != nil {
		priv = k.ECDHPriv
	}
	b, err := x509.MarshalPKCS8PrivateKey(priv)
	if err != nil {
		return nil, err
	}
	if password == nil {
		return pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: b}), nil
	}
	if b, err = encryptPKCS8(b, password); err != nil {
		return nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "ENCRYPTED PRIVATE KEY", Bytes: b}), nil
}

func (k *Key) SigTLV() uint8 {
	switch k.Kind {
	case KindRSA:
		if k.rsaBits() == 3072 {
			return tlvRSA3072
		}
		return tlvRSA2048
	case KindECDSA256, KindECDSA384:
		return tlvECDSASIG
	}
	return tlvED25519
}

func (k *Key) sigLen() int {
	switch k.Kind {
	case KindRSA:
		return k.rsaBits() / 8
	case KindECDSA256:
		return 72
	case KindECDSA384:
		return 103
	}
	return 64
}

// AllowedSHA lists the hash selections valid for this key.
func (k *Key) AllowedSHA(pure bool) []string {
	switch k.Kind {
	case KindECDSA384:
		return []string{"384"}
	case KindECDSA256:
		if k.HasPrivate() {
			return []string{"256"}
		}
		return []string{"256", "512"}
	case KindRSA:
		return []string{"256"}
	}
	if pure && k.HasPrivate() {
		return []string{"512"}
	}
	return []string{"256", "512"}
}

func newHash(sha string) hash.Hash {
	switch sha {
	case "384":
		return sha512.New384()
	case "512":
		return sha512.New()
	}
	return sha256.New()
}

func digestOf(sha string, data []byte) []byte {
	h := newHash(sha)
	h.Write(data)
	return h.Sum(nil)
}

// ecdsaSHA is the hash used when signing the payload directly.
func (k *Key) ecdsaSHA() string {
	if k.Kind == KindECDSA384 {
		return "384"
	}
	return "256"
}

// Sign signs the full payload (RSA/ECDSA) or the digest (Ed25519, unless pure).
func (k *Key) Sign(payload, digest []byte, pure, padSig bool) ([]byte, error) {
	switch k.Kind {
	case KindX25519:
		return nil, errors.New("X25519 keys can not be used for signing")
	case KindRSA:
		d := sha256.Sum256(payload)
		return rsa.SignPSS(rand.Reader, k.Priv.(*rsa.PrivateKey), crypto.SHA256, d[:],
			&rsa.PSSOptions{SaltLength: 32})
	case KindECDSA256, KindECDSA384:
		sig, err := ecdsa.SignASN1(rand.Reader, k.Priv.(*ecdsa.PrivateKey), digestOf(k.ecdsaSHA(), payload))
		if err != nil {
			return nil, err
		}
		if padSig && len(sig) < k.sigLen() {
			sig = append(sig, make([]byte, k.sigLen()-len(sig))...)
		}
		return sig, nil
	}
	msg := digest
	if pure {
		msg = payload
	}
	return ed25519.Sign(k.Priv.(ed25519.PrivateKey), msg), nil
}

// Verify checks sig over payload (RSA/ECDSA) or over digest/payload (Ed25519).
func (k *Key) Verify(sig, payload, digest []byte, pure bool) bool {
	switch k.Kind {
	case KindRSA:
		d := sha256.Sum256(payload)
		return rsa.VerifyPSS(k.Pub.(*rsa.PublicKey), crypto.SHA256, d[:], sig,
			&rsa.PSSOptions{SaltLength: 32}) == nil
	case KindECDSA256, KindECDSA384:
		if len(sig) < 2 || int(sig[1])+2 > len(sig) {
			return false
		}
		sig = sig[:sig[1]+2] // strip padding added by --pad-sig
		return ecdsa.VerifyASN1(k.Pub.(*ecdsa.PublicKey), digestOf(k.ecdsaSHA(), payload), sig)
	}
	msg := digest
	if pure {
		msg = payload
	}
	return ed25519.Verify(k.Pub.(ed25519.PublicKey), msg, sig)
}

func emitBytes(header, trailer string, b []byte, lenFormat string) string {
	var sb strings.Builder
	sb.WriteString(autogenMessage + "\n")
	sb.WriteString(header)
	for i, c := range b {
		if i%8 == 0 {
			sb.WriteString("\n    ")
		} else {
			sb.WriteString(" ")
		}
		fmt.Fprintf(&sb, "0x%02x,", c)
	}
	sb.WriteString("\n" + trailer + "\n")
	if lenFormat != "" {
		sb.WriteString(fmt.Sprintf(lenFormat, len(b)) + "\n")
	}
	return sb.String()
}

func (k *Key) EmitCPublic(suffix string) string {
	n := k.ShortName() + "_pub_key" + suffix
	return emitBytes("const unsigned char "+n+"[] = {", "};", k.PublicBytes(),
		"const unsigned int "+n+"_len = %d;")
}

func (k *Key) EmitCPublicHash(suffix string) string {
	n := k.ShortName() + "_pub_key_hash" + suffix
	h := sha256.Sum256(k.PublicBytes())
	return emitBytes("const unsigned char "+n+"[] = {", "};", h[:],
		"const unsigned int "+n+"_len = %d;")
}

func (k *Key) EmitRustPublic(suffix string) string {
	n := strings.ToUpper(k.ShortName()) + "_PUB_KEY" + strings.ToUpper(suffix)
	return emitBytes("static "+n+": &[u8] = &[", "];", k.PublicBytes(), "")
}
